def query_year_released_tracks(release_bucket: str):
    """Returns a query function for liked tracks in the given release bucket.

    release_bucket is either 'Pre-2013' (all tracks with release_year < 2013) or a
    year string like '2024' (tracks with release_year = that year).
    """
    def fn(conn):
        cur = conn.cursor()
        if release_bucket == "Pre-2013":
            cur.execute(
                """
                SELECT ls.track_uri
                FROM liked_songs ls
                INNER JOIN track_metadata tm ON tm.track_uri = ls.track_uri
                WHERE tm.release_year IS NOT NULL
                  AND tm.release_year < 2013
                ORDER BY tm.release_date ASC NULLS LAST, ls.liked_at ASC
                """
            )
        else:
            cur.execute(
                """
                SELECT ls.track_uri
                FROM liked_songs ls
                INNER JOIN track_metadata tm ON tm.track_uri = ls.track_uri
                WHERE tm.release_year = %s
                ORDER BY tm.release_date ASC NULLS LAST, ls.liked_at ASC
                """,
                (int(release_bucket),),
            )
        return [row[0] for row in cur.fetchall()]
    return fn


def query_year_discovered_tracks(discovered_year: str):
    """Returns a query function for liked tracks first discovered in the given year (or 'Undefined').

    'Discovered' = first play in spotify_plays for that track.
    'Undefined' = first played within 30 days of data start (can't tell if discovered then or earlier).
    """
    def fn(conn):
        cur = conn.cursor()
        if discovered_year == "Undefined":
            cur.execute(
                """
                WITH first_plays AS (
                    SELECT track_uri, MIN(played_at) AS first_played_at
                    FROM spotify_plays
                    WHERE track_uri IS NOT NULL
                    GROUP BY track_uri
                ),
                data_start AS (
                    SELECT MIN(played_at) + INTERVAL '30 days' AS cutoff FROM spotify_plays
                )
                SELECT fp.track_uri
                FROM first_plays fp
                INNER JOIN liked_songs ls ON ls.track_uri = fp.track_uri
                CROSS JOIN data_start ds
                WHERE fp.first_played_at < ds.cutoff
                ORDER BY fp.first_played_at ASC
                """
            )
        else:
            cur.execute(
                """
                WITH first_plays AS (
                    SELECT track_uri, MIN(played_at) AS first_played_at
                    FROM spotify_plays
                    WHERE track_uri IS NOT NULL
                    GROUP BY track_uri
                ),
                data_start AS (
                    SELECT MIN(played_at) + INTERVAL '30 days' AS cutoff FROM spotify_plays
                )
                SELECT fp.track_uri
                FROM first_plays fp
                INNER JOIN liked_songs ls ON ls.track_uri = fp.track_uri
                CROSS JOIN data_start ds
                WHERE fp.first_played_at >= ds.cutoff
                  AND EXTRACT(YEAR FROM fp.first_played_at AT TIME ZONE 'Europe/Amsterdam')::text = %s
                ORDER BY fp.first_played_at ASC
                """,
                (discovered_year,),
            )
        return [row[0] for row in cur.fetchall()]
    return fn


