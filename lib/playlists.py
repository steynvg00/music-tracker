# ── Core playlist management ───────────────────────────────────────────────────

def _ensure_playlist_metadata(sp, playlist_id: str, name: str, description: str):
    """Idempotent: set name + description."""
    full_description = f"{description} {AUTO_PLAYLIST_DESCRIPTION}"
    sp.playlist_change_details(
        playlist_id,
        name=name,
        description=full_description,
    )


def find_or_create_managed_playlist(sp, user_id: str, definition: PlaylistDefinition) -> str:
    """Find an existing playlist matching the definition's full name, falling back to legacy_name,
    or create it. Returns the playlist ID. Applies metadata (name + description) idempotently."""
    full_name = AUTO_PLAYLIST_PREFIX + definition.suffix

    print(f"[playlists] Searching for '{full_name}'...", flush=True)
    offset = 0
    current_id = None
    legacy_id = None
    n = 0
    while True:
        page = sp.current_user_playlists(limit=50, offset=offset)
        items = page["items"]
        print(f"[playlists]   page {n}: {len(items)} playlists fetched", flush=True)
        for pl in items:
            if pl["owner"]["id"] != user_id:
                continue
            if pl["name"] == full_name:
                current_id = pl["id"]
                break
            if definition.legacy_name and pl["name"] == definition.legacy_name:
                legacy_id = pl["id"]
        if current_id or page["next"] is None:
            break
        offset += 50
        n += 1

    if current_id:
        print(f"[playlists] Found '{full_name}'. Refreshing metadata...", flush=True)
        _ensure_playlist_metadata(sp, current_id, full_name, definition.description)
        return current_id

    if legacy_id:
        print(f"[playlists] Found legacy '{definition.legacy_name}'. Renaming...", flush=True)
        _ensure_playlist_metadata(sp, legacy_id, full_name, definition.description)
        print(f"[playlists] Renamed to '{full_name}'.", flush=True)
        return legacy_id

    print(f"[playlists] Not found. Creating '{full_name}'...", flush=True)
    full_description = f"{definition.description} {AUTO_PLAYLIST_DESCRIPTION}"
    new = sp.user_playlist_create(
        user=user_id,
        name=full_name,
        public=True,
        description=full_description,
    )
    _ensure_playlist_metadata(sp, new["id"], full_name, definition.description)
    print(f"[playlists] Created '{full_name}'.", flush=True)
    return new["id"]


def update_managed_playlist(sp, conn, user_id: str, definition: PlaylistDefinition) -> dict:
    """Refresh one managed playlist: find/create, run query, replace tracks.
    Returns {'name': str, 'playlist_id': str, 'track_count': int, 'action': 'created'|'updated'}."""
    full_name = AUTO_PLAYLIST_PREFIX + definition.suffix
    playlist_id = find_or_create_managed_playlist(sp, user_id, definition)
    track_uris = definition.query_fn(conn)[:definition.max_tracks]
    spotify_uris = [f"spotify:track:{uri}" if not uri.startswith("spotify:") else uri
                    for uri in track_uris]
    replace_playlist_tracks(sp, playlist_id, spotify_uris)
    return {
        "name": full_name,
        "playlist_id": playlist_id,
        "track_count": len(spotify_uris),
        "action": "updated",
    }


def replace_playlist_tracks(sp, playlist_id: str, uris: list[str]) -> None:
    """Replace the playlist's tracks with the given URIs."""
    print(f"[playlists] Replacing playlist contents with {len(uris)} tracks...", flush=True)
    if not uris:
        sp.playlist_replace_items(playlist_id, [])
        print("[playlists] Replace complete.", flush=True)
        return

    sp.playlist_replace_items(playlist_id, uris[:100])
    for i in range(100, len(uris), 100):
        batch = uris[i : i + 100]
        print(f"[playlists]   Adding batch of {len(batch)} tracks...", flush=True)
        sp.playlist_add_items(playlist_id, batch)
        print("[playlists]   Batch added.", flush=True)
    print("[playlists] Replace complete.", flush=True)
