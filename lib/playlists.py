_MONTH_NAMES = [
    "January", "February", "March", "April", "May", "June",
    "July", "August", "September", "October", "November", "December",
]

_MONTHLY_NUMBER_ONE_DESCRIPTION = (
    "Auto-managed by music-tracker. Manual edits will be overwritten on refresh."
)


def _monthly_top_one_per_month(conn) -> list[tuple[int, int, str]]:
    """One row per (year, month) with the top track URI, ordered yr ASC, mo ASC.

    Tie-breaking: on equal plays, earliest first_play_at wins (deterministic).
    """
    cur = conn.cursor()
    cur.execute(
        """
        WITH per_month AS (
            SELECT
                EXTRACT(YEAR  FROM played_at AT TIME ZONE 'Europe/Amsterdam')::int AS yr,
                EXTRACT(MONTH FROM played_at AT TIME ZONE 'Europe/Amsterdam')::int AS mo,
                track_uri,
                COUNT(*) AS plays,
                MIN(played_at) AS first_play_at
            FROM spotify_plays
            WHERE track_uri IS NOT NULL
            GROUP BY yr, mo, track_uri
        ),
        ranked AS (
            SELECT yr, mo, track_uri, plays, first_play_at,
                   ROW_NUMBER() OVER (
                       PARTITION BY yr, mo
                       ORDER BY plays DESC, first_play_at ASC
                   ) AS rn
            FROM per_month
        )
        SELECT yr, mo, track_uri
        FROM ranked
        WHERE rn = 1
        ORDER BY yr DESC, mo DESC
        """
    )
    return cur.fetchall()


def month_number_one_playlists(conn) -> list[PlaylistDefinition]:
    """12 PlaylistDefinitions — one per calendar month, each holding that month's #1
    track across all years, ordered by year ASC.
    """
    rows = _monthly_top_one_per_month(conn)

    def make_query_fn(uris):
        def fn(_conn):
            return uris
        return fn

    definitions = []
    for mo_num in range(1, 13):
        month_name = _MONTH_NAMES[mo_num - 1]
        month_uris = [uri for yr, mo, uri in rows if mo == mo_num]
        definitions.append(
            PlaylistDefinition(
                suffix=f"My {month_name} #1",
                description=_MONTHLY_NUMBER_ONE_DESCRIPTION,
                query_fn=make_query_fn(month_uris),
                kind="updating",
            )
        )

    return definitions


def rolling_monthly_number_one_playlist(conn) -> list[PlaylistDefinition]:
    """One PlaylistDefinition — the #1 track of every COMPLETED month, reverse-chronological
    (newest month first, newest prepended at the top). Grows by one entry each month.

    v0.72.1: newest-month-first so Spotify's "Sort by: Recently added" surfaces the most
    recent monthly #1 at the top. (v0.72 shipped oldest-first, which fought that sort.)

    v0.72: the in-progress current month is excluded (its #1 is not final yet), so this
    playlist is the frozen historical chain that grows on the 1st of each month when the
    just-ended month's #1 becomes final — equivalent to prepending the #1 of that month's
    Top 25 · Month snapshot. Refreshed by the monthly 1st-of-month cron. Full-chain replace
    is idempotent (a missed month self-heals) and produces exactly the prepend-one semantics
    while the only new element is the just-completed month.
    """
    rows = _monthly_top_one_per_month(conn)  # yr DESC, mo DESC

    now_local = datetime.now(TZ_AMSTERDAM)
    current_ym = (now_local.year, now_local.month)
    completed = [(yr, mo, uri) for yr, mo, uri in rows if (yr, mo) < current_ym]
    completed.sort(key=lambda r: (r[0], r[1]), reverse=True)  # reverse-chronological (newest first)
    all_uris = [uri for _yr, _mo, uri in completed]

    def query_fn(_conn):
        return all_uris

    return [
        PlaylistDefinition(
            suffix="My Monthly #1",
            description=(
                "Auto-managed by music-tracker. The #1 track of each completed month, "
                "newest first — one new track added to the top every 1st of the month."
            ),
            query_fn=query_fn,
            kind="updating",
            cadence="monthly",  # v0.72: weekly → monthly 1st-of-month refresh
        )
    ]


_FORGOTTEN_FAVORITES_MIN_PLAYS = 50
_FORGOTTEN_FAVORITES_UNTOUCHED_DAYS = 730  # v0.72: 365 → 730 (2 years — a real "forgotten" bar)


def forgotten_favorites_playlist(conn) -> list[PlaylistDefinition]:
    """One PlaylistDefinition — liked tracks with 50+ plays not played in 365 days,
    ordered by play count DESC. Full refresh every run.
    """
    min_plays = _FORGOTTEN_FAVORITES_MIN_PLAYS
    days = _FORGOTTEN_FAVORITES_UNTOUCHED_DAYS

    def query_fn(conn):
        cur = conn.cursor()
        cur.execute(
            """
            WITH play_stats AS (
                SELECT
                    track_uri,
                    COUNT(*) AS plays,
                    MAX(played_at) AS last_played_at
                FROM spotify_plays
                WHERE track_uri IS NOT NULL
                GROUP BY track_uri
            )
            SELECT ps.track_uri
            FROM play_stats ps
            JOIN liked_songs ls ON ls.track_uri = ps.track_uri
            WHERE ps.plays >= %s
              AND ps.last_played_at < NOW() - make_interval(days => %s)
            ORDER BY ps.plays DESC
            """,
            (min_plays, days),
        )
        return [row[0] for row in cur.fetchall()]

    years = days // 365
    return [
        PlaylistDefinition(
            suffix="Forgotten favorites",
            description=(
                f"Auto-managed by music-tracker. Tracks with {min_plays}+ plays you haven't "
                f"returned to in {years} years. Re-discovery candidates."
            ),
            query_fn=query_fn,
            kind="updating",
            cadence="mid_month",  # v0.72: weekly → 15th-of-month refresh
        )
    ]


