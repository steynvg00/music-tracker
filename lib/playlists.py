def year_discovered_playlists(conn) -> list[PlaylistDefinition]:
    """Generate one PlaylistDefinition per discovery year for liked songs.

    Returns 'Undefined' first (for tracks already in library at data start), then years ascending.
    """
    cur = conn.cursor()
    cur.execute(
        """
        WITH first_plays AS (
            SELECT track_uri, MIN(played_at) AS first_played_at
            FROM spotify_plays
            WHERE track_uri IS NOT NULL
            GROUP BY track_uri
        ),
        data_start AS (
            SELECT MIN(played_at) + INTERVAL '30 days' AS cutoff FROM spotify_plays
        ),
        liked_first_plays AS (
            SELECT fp.track_uri, fp.first_played_at, ds.cutoff
            FROM first_plays fp
            INNER JOIN liked_songs ls ON ls.track_uri = fp.track_uri
            CROSS JOIN data_start ds
        ),
        classified AS (
            SELECT
                CASE
                    WHEN first_played_at < cutoff THEN 'Undefined'
                    ELSE EXTRACT(YEAR FROM first_played_at AT TIME ZONE 'Europe/Amsterdam')::text
                END AS discovered_year
            FROM liked_first_plays
        )
        SELECT discovered_year, COUNT(*) AS cnt
        FROM classified
        GROUP BY discovered_year
        HAVING COUNT(*) > 0
        ORDER BY
            CASE WHEN discovered_year = 'Undefined' THEN 0 ELSE 1 END,
            discovered_year
        """
    )
    rows = cur.fetchall()

    definitions = []
    for discovered_year, _count in rows:
        suffix = f"{discovered_year} · Discovered"
        if discovered_year == "Undefined":
            description = (
                "Liked tracks already in your library when data collection started "
                "(Feb 2017) — exact discovery year unknown."
            )
        else:
            description = (
                f"Liked tracks you discovered in {discovered_year} — first heard that year, "
                "ordered by first-play date."
            )

        definitions.append(
            PlaylistDefinition(
                suffix=suffix,
                description=description,
                query_fn=query_year_discovered_tracks(discovered_year),
                kind="updating",
            )
        )

    return definitions


def get_managed_playlists(conn) -> list[PlaylistDefinition]:
    """Return all managed playlist definitions (static + dynamic).

    Static playlists are constants. Dynamic playlists are generated from current data
    by factory functions that take a DB connection.
    """
    dynamic = []
    dynamic.extend(year_discovered_playlists(conn))
    return STATIC_PLAYLISTS + dynamic


# ── Core playlist management ───────────────────────────────────────────────────

def _ensure_playlist_metadata(sp, playlist_id: str, name: str, description: str):
    """Idempotent: set name + description (description already fully built by caller)."""
    sp.playlist_change_details(
        playlist_id,
        name=name,
        description=description,
    )


def find_or_create_managed_playlist(sp, user_id: str, definition: PlaylistDefinition) -> str:
    """Find an existing playlist matching the definition's full name, falling back to legacy_names,
    or create it. Returns the playlist ID. Applies metadata (name + description) idempotently."""
    full_name = get_full_name(definition)
    full_description = get_full_description(definition)

    print(f"[playlists] Searching for '{full_name}'...", flush=True)
    offset = 0
    current_id = None
    legacy_id = None
    legacy_matched_name = None
    n = 0
    while True:
        page = sp.current_user_playlists(limit=50, offset=offset)
        items = page["items"]
        print(f"[playlists]   page {n}: {len(items)} playlists fetched", flush=True)
        for pl in items:
            if pl["owner"]["id"] != user_id:
                continue
            if pl["name"] == full_name:
                current_id = pl["id"]
                break
            if legacy_id is None:
                for legacy_name in definition.legacy_names:
                    if pl["name"] == legacy_name:
                        legacy_id = pl["id"]
                        legacy_matched_name = legacy_name
                        break
        if current_id or page["next"] is None:
            break
        offset += 50
        n += 1

    if current_id:
        print(f"[playlists] Found '{full_name}'. Refreshing metadata...", flush=True)
        _ensure_playlist_metadata(sp, current_id, full_name, full_description)
        return current_id

    if legacy_id:
        print(f"[playlists] Found legacy '{legacy_matched_name}'. Renaming...", flush=True)
        _ensure_playlist_metadata(sp, legacy_id, full_name, full_description)
        print(f"[playlists] Renamed to '{full_name}'.", flush=True)
        return legacy_id

    print(f"[playlists] Not found. Creating '{full_name}'...", flush=True)
    new = sp.user_playlist_create(
        user=user_id,
        name=full_name,
        public=True,
        description=full_description,
    )
    _ensure_playlist_metadata(sp, new["id"], full_name, full_description)
    print(f"[playlists] Created '{full_name}'.", flush=True)
    return new["id"]


def update_managed_playlist(sp, conn, user_id: str, definition: PlaylistDefinition) -> dict:
    """Refresh one managed playlist: find/create, run query, replace tracks.
    Returns {'name': str, 'playlist_id': str, 'track_count': int, 'action': 'created'|'updated'}."""
    full_name = get_full_name(definition)
    playlist_id = find_or_create_managed_playlist(sp, user_id, definition)
    track_uris = definition.query_fn(conn)[:definition.max_tracks]
    spotify_uris = [f"spotify:track:{uri}" if not uri.startswith("spotify:") else uri
                    for uri in track_uris]
    replace_playlist_tracks(sp, playlist_id, spotify_uris)
    return {
        "name": full_name,
        "playlist_id": playlist_id,
        "track_count": len(spotify_uris),
        "action": "updated",
    }


def replace_playlist_tracks(sp, playlist_id: str, uris: list[str]) -> None:
    """Replace the playlist's tracks with the given URIs."""
    print(f"[playlists] Replacing playlist contents with {len(uris)} tracks...", flush=True)
    if not uris:
        sp.playlist_replace_items(playlist_id, [])
        print("[playlists] Replace complete.", flush=True)
        return

    sp.playlist_replace_items(playlist_id, uris[:100])
    for i in range(100, len(uris), 100):
        batch = uris[i : i + 100]
        print(f"[playlists]   Adding batch of {len(batch)} tracks...", flush=True)
        sp.playlist_add_items(playlist_id, batch)
        print("[playlists]   Batch added.", flush=True)
    print("[playlists] Replace complete.", flush=True)
