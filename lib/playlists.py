# Playlist helpers for music-tracker.
#
# SAFETY CONTRACT: modification calls (playlist_replace_items, playlist_add_items)
# are ONLY ever made on the playlist id returned by find_or_create_managed_playlist.
# The following spotipy methods are explicitly forbidden in this module and must
# never be added: playlist_remove_all_occurrences_of_items,
# playlist_remove_specific_occurrences_of_items, user_playlist_remove_*,
# current_user_unfollow_playlist.

AUTO_PLAYLIST_PREFIX = "🤖 Auto · "
AUTO_PLAYLIST_DESCRIPTION = (
    "Auto-generated by music-tracker. Manual edits will be overwritten on the next refresh."
)


# ── Dataclass ─────────────────────────────────────────────────────────────────

@dataclass
class PlaylistDefinition:
    """A definition for one managed auto-playlist."""
    suffix: str                                          # e.g. "100+ plays" → full name "🤖 Auto · 100+ plays"
    description: str                                     # per-playlist tagline; combined with AUTO_PLAYLIST_DESCRIPTION
    query_fn: Callable[[psycopg.Connection], list[str]]  # returns list of track_uris in desired order
    max_tracks: int = 10000                              # safety cap (Spotify max is 10000 per playlist)
    legacy_name: Optional[str] = None                   # if set, also search for this name and rename it


# ── Query helpers ─────────────────────────────────────────────────────────────

def query_plays_threshold_at_least(min_plays: int, limit: int = 10000):
    """Tracks with at least min_plays plays, ordered by plays DESC."""
    def fn(conn):
        cur = conn.cursor()
        cur.execute(
            """
            SELECT track_uri
            FROM spotify_plays
            WHERE track_uri IS NOT NULL
            GROUP BY track_uri
            HAVING COUNT(*) >= %s
            ORDER BY COUNT(*) DESC
            LIMIT %s
            """,
            (min_plays, limit),
        )
        return [row[0] for row in cur.fetchall()]
    return fn


def query_plays_threshold_band(min_plays: int, max_plays: int, limit: int = 10000):
    """Tracks with plays in [min_plays, max_plays], ordered by plays DESC."""
    def fn(conn):
        cur = conn.cursor()
        cur.execute(
            """
            SELECT track_uri
            FROM spotify_plays
            WHERE track_uri IS NOT NULL
            GROUP BY track_uri
            HAVING COUNT(*) BETWEEN %s AND %s
            ORDER BY COUNT(*) DESC
            LIMIT %s
            """,
            (min_plays, max_plays, limit),
        )
        return [row[0] for row in cur.fetchall()]
    return fn


def query_top_recent(days: int, limit: int):
    """Top tracks by plays in the last `days` days."""
    def fn(conn):
        cur = conn.cursor()
        cur.execute(
            """
            SELECT track_uri
            FROM spotify_plays
            WHERE track_uri IS NOT NULL
              AND played_at >= NOW() - (INTERVAL '1 day' * %s)
            GROUP BY track_uri
            ORDER BY COUNT(*) DESC
            LIMIT %s
            """,
            (days, limit),
        )
        return [row[0] for row in cur.fetchall()]
    return fn


def query_top_current_year(limit: int):
    """Top tracks by plays in current local year (Europe/Amsterdam)."""
    def fn(conn):
        cur = conn.cursor()
        cur.execute(
            """
            SELECT track_uri
            FROM spotify_plays
            WHERE track_uri IS NOT NULL
              AND EXTRACT(YEAR FROM played_at AT TIME ZONE 'Europe/Amsterdam')::int =
                  EXTRACT(YEAR FROM (NOW() AT TIME ZONE 'Europe/Amsterdam'))::int
            GROUP BY track_uri
            ORDER BY COUNT(*) DESC
            LIMIT %s
            """,
            (limit,),
        )
        return [row[0] for row in cur.fetchall()]
    return fn


def query_top_all_time(limit: int):
    """Top tracks all-time."""
    def fn(conn):
        cur = conn.cursor()
        cur.execute(
            """
            SELECT track_uri
            FROM spotify_plays
            WHERE track_uri IS NOT NULL
            GROUP BY track_uri
            ORDER BY COUNT(*) DESC
            LIMIT %s
            """,
            (limit,),
        )
        return [row[0] for row in cur.fetchall()]
    return fn


