UPDATING_NAME_SUFFIX = " · Auto 🤖🔄"
SNAPSHOT_NAME_SUFFIX = " · Auto 🤖📸"

AUTO_PLAYLIST_DESCRIPTION_UPDATING = (
    "Auto-generated by music-tracker. Manual edits will be overwritten on the next refresh."
)
AUTO_PLAYLIST_DESCRIPTION_SNAPSHOT = (
    "Auto-generated snapshot by music-tracker. This playlist is frozen and will not be updated."
)


# ── Dataclass ─────────────────────────────────────────────────────────────────

@dataclass
class PlaylistDefinition:
    """A definition for one managed auto-playlist."""
    suffix: str                                          # e.g. "100+ plays" → full name "100+ plays · Auto 🤖🔄"
    description: str                                     # per-playlist tagline
    query_fn: Callable[[psycopg.Connection], list[str]]  # returns list of track_uris in desired order
    kind: str = "updating"                               # "updating" or "snapshot"
    max_tracks: int = 10000                              # safety cap (Spotify max is 10000 per playlist)
    # v0.72: which cron refreshes this updating playlist. "weekly" (Mon 06:00) is the default;
    # "monthly" (1st of month), "mid_month" (15th) and "daily" playlists are routed to their own
    # cron entry points by filtering on this field. Ignored for snapshots.
    cadence: str = "weekly"
    legacy_names: list[str] = field(default_factory=list)  # chain of past names, tried in order
    # v0.66: for Top playlists, returns {track_uri: plays_in_the_playlist's_window} for the
    # given uris — the SCOPE-CORRECT count shown in the weekly digest (e.g. last-30-day plays
    # for "Top 50 last 30 days"). None → digest renders "—" instead of a misleading all-time count.
    plays_count_fn: Optional[Callable[[psycopg.Connection, list[str]], dict[str, int]]] = None


# ── Name/description helpers ───────────────────────────────────────────────────

def get_full_name(definition: PlaylistDefinition) -> str:
    """Build the full Spotify playlist name from a definition."""
    suffix = SNAPSHOT_NAME_SUFFIX if definition.kind == "snapshot" else UPDATING_NAME_SUFFIX
    return f"{definition.suffix}{suffix}"


def get_full_description(definition: PlaylistDefinition) -> str:
    """Build the full Spotify playlist description from a definition."""
    boilerplate = (
        AUTO_PLAYLIST_DESCRIPTION_SNAPSHOT if definition.kind == "snapshot"
        else AUTO_PLAYLIST_DESCRIPTION_UPDATING
    )
    return f"{definition.description} {boilerplate}"


